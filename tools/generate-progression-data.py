#!/usr/bin/env python3
"""Generate frontend/src/lib/progression-data.ts from the game's own
research-skill and collectible entity tables.

Source (found 2026-10-23, see docs/development/journal.md): the tables are
NOT in the APK's Addressables bundles or the Zodiac remote config. They
ship as standalone serialized assets inside assets/bin/Data of the base
APK (one GUID-named file per entity asset) in game 5.64.1 (release dir
~/mineops-data/releases/5.64.1_97855_20261008T164225Z on ubuntumac).
Extracted with UnityPy + TypeTreeGeneratorAPI on ubuntumac into
~/mineops-re/entity-dump/*.json; copies live in this repo's gitignored
.re-dump/entities/ (raw dumps stay out of git).

Tables used:
  SkillNode     {SkillID, ParentId, EffectId, SkillPathID, MaxLevel, ...}
                EffectId is the SkillNodeType enum (dump.cs): 1 SingleMine,
                2 AllMines, 14 ContinentMines, 24 WarehouseLoadingSpeed,
                25 WarehouseCapacity, 26 ElevatorLoadingSpeed,
                27 ElevatorCapacity, 28 CorridorGainPerSecond,
                29 CorridorCapacity.
  SkillLevels   {SkillID, SkillLevel, ParamX, ParamY, SkillPoints}
                ParamX is the CUMULATIVE factor at that level; ParamY is a
                constant target selector per skill (mine number for
                SingleMine, continentType for ContinentMines/leg-speed
                nodes) and is taken from SkillNode-adjacent level rows.
  Collectibles  {CollectibleID, CollectibleType, ...} - Corridor (shaft),
                Ground (warehouse: the save's Ground carries the warehouse
                worker count), Elevator.
  CollectibleProductionFactors {CollectibleID, CollectibleLevel,
                ProductionFactor, ...} - ProductionFactor per level.
                ABProductionFactor is an A/B-test variant and is NOT
                emitted; SecondaryEffectFactor is NOT emitted (its target
                semantics are not pinned - see progression.ts).

Regenerate:
  python3 tools/generate-progression-data.py
(after refreshing .re-dump/entities/ from ubuntumac ~/mineops-re/entity-dump/)
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / ".re-dump" / "entities"
OUT = ROOT / "frontend" / "src" / "lib" / "progression-data.ts"

PRODUCTION_EFFECTS = {1, 2, 14, 24, 25, 26, 27, 28, 29}


def load(name):
    with open(SRC / f"{name}.json") as fh:
        return json.load(fh)["Params"]


def main():
    nodes = {row["SkillID"]: row for row in load("SkillNode")}
    levels_by_skill = {}
    for row in load("SkillLevels"):
        levels_by_skill.setdefault(row["SkillID"], {})[row["SkillLevel"]] = (
            row["ParamX"],
            row["ParamY"],
        )

    skills = {}
    for sid, node in sorted(nodes.items()):
        effect = node["EffectId"]
        if effect not in PRODUCTION_EFFECTS:
            continue
        rows = levels_by_skill.get(sid)
        if not rows:
            continue
        max_level = max(rows)
        x = [rows.get(lvl, (1.0, None))[0] for lvl in range(max_level + 1)]
        target = rows[max_level][1]
        skills[sid] = {"effect": effect, "target": target, "x": x}

    collectible_types = {row["CollectibleID"]: row["CollectibleType"] for row in load("Collectibles")}
    factors = {}
    for row in load("CollectibleProductionFactors"):
        factors.setdefault(row["CollectibleID"], {})[row["CollectibleLevel"]] = row["ProductionFactor"]
    collectibles = {}
    for cid, ctype in sorted(collectible_types.items()):
        rows = factors.get(cid)
        if not rows:
            continue
        max_level = max(rows)
        collectibles[cid] = {
            "type": ctype,
            "f": [rows.get(lvl, 1.0) for lvl in range(max_level + 1)],
        }

    header = """/**
 * GENERATED by tools/generate-progression-data.py - do not edit by hand.
 *
 * The game's research-skill and collectible production tables, extracted
 * from the game's own entity assets (game 5.64.1, assets/bin/Data
 * standalone serialized files; see the generator for provenance).
 *
 * SKILL_PRODUCTION: per skill id, the SkillNodeType effect id, the
 * target selector (ParamY: mine number for SingleMine, continentType
 * for ContinentMines and the per-leg speed nodes), and the cumulative
 * factor ParamX at each skill level (index = level, level 0 = 1).
 * Only production effects are emitted: 1 SingleMine, 2 AllMines,
 * 14 ContinentMines, 24 WarehouseLoadingSpeed, 25 WarehouseCapacity,
 * 26 ElevatorLoadingSpeed, 27 ElevatorCapacity, 28 CorridorGainPerSecond,
 * 29 CorridorCapacity. (progression.ts applies the rate subset; the
 * capacity effects have no trip mechanics to act on in this model.)
 *
 * COLLECTIBLE_PRODUCTION: per collectible id, its leg type (Corridor =
 * mineshaft, Ground = warehouse, Elevator) and the ProductionFactor at
 * each collectible level (index = level). ABProductionFactor (A/B-test
 * variant) and SecondaryEffectFactor are deliberately not emitted.
 */
"""
    body = [
        "export interface SkillProductionRow { effect: number; target: number; x: number[] }",
        f"export const SKILL_PRODUCTION: Record<number, SkillProductionRow> = {json.dumps(skills, separators=(',', ':'))};",
        "",
        "export interface CollectibleProductionRow { type: string; f: number[] }",
        f"export const COLLECTIBLE_PRODUCTION: Record<number, CollectibleProductionRow> = {json.dumps(collectibles, separators=(',', ':'))};",
        "",
    ]
    OUT.write_text(header + "\n".join(body))
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes): {len(skills)} skills, {len(collectibles)} collectibles")


if __name__ == "__main__":
    main()
